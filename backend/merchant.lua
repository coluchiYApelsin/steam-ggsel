local millennium=require("millennium")
local fs=require("fs")
local hooks={}
local M={}
function M.start()
    -- Native Millennium resolves browser hook files under millennium/themes.
    -- This harmless owned marker also opts the GGSEL origin into WebKit injection.
    local dir=millennium.get_install_path().."/themes/steam-ggsel-integration"
    fs.create_directories(dir)
    local file=assert(io.open(dir.."/enable-v1.css","w"))
    file:write("/* Generated by Steam GGSEL. Styles are scoped in the WebKit module. */\n")
    file:close()
    hooks[1]=millennium.add_browser_css("steam-ggsel-integration/enable-v1.css","^https://ggsel[.]net/.*$")
    assert(hooks[1] and hooks[1]>=0,"GGSEL origin hook registration failed")
end
function M.stop()
    for _,id in ipairs(hooks) do pcall(millennium.remove_browser_module,id) end
    hooks={}
end
return M
